/**
 * 입력 정규화 회귀 테스트.
 *
 * 왜 여기에 테스트를 두는가: analysis.ts 의 normalize() 안에 폭 없는 문자를 걸러내는
 * 문자 클래스가 있는데, 그 범위가 소스에 **보이지 않는 문자 그대로** 적혀 있다.
 * 화면으로는 `[-]` 처럼만 보이고 무엇이 걸러지는지 알 수 없다.
 *
 * 이 프로젝트는 보이지 않는 문자로 두 번 크게 헤맸다.
 *  - 한자 범위를 리터럴로 적다가 U+F900 대신 U+8C48 을 써서 한글이 한자로 판정됐다.
 *  - 캐시 키 조립 문자열에 널 문자(U+0000)가 구분자로 들어가 정규식 교체가 세 번 실패했다.
 * 그래서 어떤 코드포인트가 실제로 걸러지는지를 숫자로 명시해 고정해 둔다.
 * 이 파일에는 보이지 않는 문자를 리터럴로 적지 않는다 — 주석에도 적지 않는다.
 *
 * 이 테스트는 **현재 동작을 기록**한다. 코드를 고치지 않는다. 범위 밖이라 남는 문자도
 * 남는 그대로 적어 둔다 — 나중에 그것이 문제가 되면 이 기록을 근거로 고칠 수 있다.
 */
import { describe, it, expect } from 'vitest';
import { normalize } from '../src/lib/analysis';

const ch = (cp: number) => String.fromCodePoint(cp);

describe('normalize — 폭 없는 문자', () => {
  // 문자 클래스에 실제로 적힌 범위는 U+200B–U+200D 와 U+FEFF 다.
  it.each([
    ['U+200B ZERO WIDTH SPACE', 0x200b],
    ['U+200C ZERO WIDTH NON-JOINER', 0x200c],
    ['U+200D ZERO WIDTH JOINER', 0x200d],
  ])('%s 를 제거한다', (_label, cp) => {
    expect(normalize(`學${ch(cp)}而`)).toBe('學而');
  });

  it('여러 개가 섞여 있어도 모두 제거한다', () => {
    expect(normalize(`學${ch(0x200b)}${ch(0x200c)}而${ch(0x200d)}`)).toBe('學而');
  });

  /**
   * 현 동작 기록 — U+FEFF 는 제거되지 않고 **공백 한 칸으로 바뀐다**.
   *
   * 문자 클래스에 U+FEFF 가 적혀 있지만 그 replace 는 U+FEFF 를 볼 일이 없다.
   * 앞선 `.replace(/\s+/g, ' ')` 가 먼저 돌고, 자바스크립트의 `\s` 에는 U+FEFF 가
   * 포함되기 때문이다 (`\s` 의 정의에 U+FEFF 가 들어 있다. U+200B~U+200D 는 들어
   * 있지 않다 — `\s` 의 범위는 U+2000~U+200A 에서 끝난다). 즉 문자 클래스에 적힌
   * U+FEFF 는 닿지 않는 코드다.
   *
   * 결과: 글자 사이에 U+FEFF 가 끼면 없던 공백이 생겨 정규화 결과가 갈라지고,
   * 캐시 키도 갈라져 같은 구절이 두 번 과금될 수 있다. 화면에는 폭이 없어 보이지
   * 않으므로 사람이 알아채기 어렵다.
   *
   * 지금은 고치지 않고 사실만 고정한다. 고칠 때는 이 테스트가 바뀌는 것이 정상이다.
   */
  it('U+FEFF 는 제거되지 않고 공백으로 바뀐다 — 현 동작 기록', () => {
    expect(normalize(`學${ch(0xfeff)}而`)).toBe('學 而');
  });

  it('앞뒤의 U+FEFF 는 공백이 된 뒤 trim 되어 사라진다 — 현 동작 기록', () => {
    expect(normalize(`${ch(0xfeff)}學而${ch(0xfeff)}`)).toBe('學而');
  });

  /**
   * 현 동작 기록 — U+2060(WORD JOINER)은 문자 클래스 범위 밖이고 `\s` 에도 없어
   * 그대로 남는다. U+FEFF 와 같은 이유로 캐시 키를 갈라놓을 수 있다.
   */
  it('U+2060(WORD JOINER)은 그대로 남는다 — 현 동작 기록', () => {
    expect(normalize(`學${ch(0x2060)}而`)).toBe(`學${ch(0x2060)}而`);
  });
});

describe('normalize — 공백', () => {
  it('연속 공백을 하나로 줄인다', () => {
    expect(normalize('學而   時習之')).toBe('學而 時習之');
  });

  it('줄바꿈과 탭도 공백 하나로 취급한다', () => {
    expect(normalize('學而\n\t時習之')).toBe('學而 時習之');
  });

  it('앞뒤 공백을 없앤다', () => {
    expect(normalize('  學而時習之  ')).toBe('學而時習之');
  });

  // 캐시 키에 쓰이므로 이 성질이 곧 "같은 구절을 두 번 과금하지 않는다" 이다.
  it('공백만 다른 두 입력이 같은 결과가 된다', () => {
    expect(normalize(' 學而  時習之 ')).toBe(normalize('學而 時習之'));
  });

  it('구두점은 건드리지 않는다', () => {
    expect(normalize('知之爲知之, 不知爲不知, 是知也')).toBe('知之爲知之, 不知爲不知, 是知也');
  });
});
